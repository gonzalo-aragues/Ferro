import AppKit

struct ClipItem: Identifiable, Equatable {
    enum Kind: Equatable {
        case text(String)
        case image(URL)
        case files([URL])
    }
    let id = UUID()
    let kind: Kind
    var date: Date
    var pinned = false

    var preview: String {
        switch kind {
        case .text(let s): s.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " ⏎ ")
        case .image: "Image"
        case .files(let u): u.count == 1 ? u[0].lastPathComponent : "\(u.count) files"
        }
    }
    var icon: String {
        switch kind {
        case .text(let s): s.hasPrefix("http") ? "link" : "text.alignleft"
        case .image: "photo"
        case .files: "doc"
        }
    }
}

/// Clipboard history. Skips items password managers mark as concealed/transient.
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    var onCopiedFromIsland: (() -> Void)?

    private let pb = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?
    private let limit = 40
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]

    var sorted: [ClipItem] { items.filter(\.pinned) + items.filter { !$0.pinned } }

    init() {
        lastChange = pb.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in self?.check() }
    }

    private func check() {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes) else { return }

        var kind: ClipItem.Kind?
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            kind = .files(urls)
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            kind = .text(s)
        } else if let img = NSImage(pasteboard: pb), let u = ShelfStore.saveImage(img, prefix: "Clip") {
            kind = .image(u)
        }
        guard let kind else { return }
        insert(kind)
    }

    private func insert(_ kind: ClipItem.Kind) {
        var pinned = false
        if let i = items.firstIndex(where: { $0.kind == kind }) {
            pinned = items[i].pinned
            items.remove(at: i)
        }
        items.insert(ClipItem(kind: kind, date: Date(), pinned: pinned), at: 0)
        var unpinned = 0
        items.removeAll { item in
            guard !item.pinned else { return false }
            unpinned += 1
            if unpinned > limit { deleteFile(item); return true }
            return false
        }
    }

    func copy(_ item: ClipItem) {
        pb.clearContents()
        switch item.kind {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let u): if let img = NSImage(contentsOf: u) { pb.writeObjects([img]) }
        case .files(let us): pb.writeObjects(us as [NSURL])
        }
        lastChange = pb.changeCount
        if let i = items.firstIndex(of: item) {
            var moved = items.remove(at: i)
            moved.date = Date()
            items.insert(moved, at: 0)
        }
        onCopiedFromIsland?()
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteFile(item)
    }

    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(deleteFile)
        items.removeAll { !$0.pinned }
    }

    private func deleteFile(_ item: ClipItem) {
        if case .image(let u) = item.kind { try? FileManager.default.removeItem(at: u) }
    }

    func provider(for item: ClipItem) -> NSItemProvider {
        switch item.kind {
        case .text(let s): NSItemProvider(object: s as NSString)
        case .image(let u): NSItemProvider(contentsOf: u) ?? NSItemProvider()
        case .files(let us): NSItemProvider(contentsOf: us[0]) ?? NSItemProvider()
        }
    }
}
